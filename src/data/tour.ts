/**
 * Find a single tour by its URL slug.
 * Usage: getTourBySlug('sintra-half-day-private-experience')
 */
export function getTourBySlug(slug: string): Tour | undefined {
  return tours.find((t) => t.page_item_url === slug)
}

/**
 * Filter tours by activityType.
 * Common values: 'Day tour / activity' | 'Transportation'
 */
export function getToursByType(type: string): Array<Tour> {
  return tours.filter((t) => t.data.activityType === type)
}

/**
 * Filter tours by a category value.
 * e.g. getToursByCategory('Cultural and theme tours')
 */
export function getToursByCategory(category: string): Array<Tour> {
  return tours.filter((t) =>
    t.data.activityCategories.some((c) => c.value === category)
  )
}

/**
 * Parse the defaultPrice string to a numeric value.
 * e.g. parseTourPrice('EUR 470.00') => 470
 */
export function parseTourPrice(price: string): number {
  return parseFloat(price.replace(/[^0-9.]/g, ''))
}

export function mapToTourCard(tour: Tour): TourCardTour {
  return {
    id: String(tour.data.id),
    slug: tour.page_item_url,
    title: tour.data.title,
    images: [
      { src: tour.data.keyPhoto, alt: tour.data.title },
      ...tour.data.otherPhotos.slice(0, 2).map((p) => ({
        src: p.originalUrl,
        alt: p.description,
      })),
    ],
    duration: tour.data.durationText,
    departureFrom: tour.data.meetingType,
    description: tour.data.excerpt || tour.data.description.replace(/<[^>]*>/g, '').slice(0, 120) + '…',
    price: parseTourPrice(tour.data.defaultPrice),
    isOnDemand: false,
  }
}